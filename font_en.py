GLYPHS = {}
for ch, rows in _CAPS.items():
    GLYPHS[ch] = (1, rows)
GLYPHS.update(_LOWER)

# characters that get rewritten before encoding
NORMALIZE = {'’': "'", '‘': "'", '“': '"', '”': '"', '…': '...', '—': '-', '–': '-', '~': '-', '　': ' '}


def normalize(text):
    for a, b in NORMALIZE.items():
        text = text.replace(a, b)
    return text


def cell(ch):
    """8x16 list of 0/1 rows for one character."""
    top, rows = GLYPHS[ch]
    grid = [[0] * 8 for _ in range(16)]
    for r, line in enumerate(rows):
        for c, px in enumerate(line):
            if px == '#':
                grid[1 + top + r][1 + c] = 1
    return grid


def tile_bytes(pair):
    """FONT16 tile (128 bytes, 4bpp) showing two characters side by side."""
    left, right = cell(pair[0]), cell(pair[1])
    out = bytearray()
    for y in range(16):
        row = left[y] + right[y]
        for x in range(0, 16, 2):
            out.append(((COLOR if row[x] else 0) << 4) | (COLOR if row[x + 1] else 0))
    return bytes(out)


def pairs_of(line):
    """Split a line into 2-character pairs (pads with a space)."""
    if len(line) % 2:
        line += ' '
    return [line[i:i + 2] for i in range(0, len(line), 2)]


# --- runtime letter pairs (patch_code.py) ---------------------------------------------------------------
# Text encodes each pair of characters as one glyph code; the patched font16_decode_glyph builds the 16x16
# tile at run time from a 1-bit half-width font (8x16, 16 bytes per char, ASCII 0x20-0x7E) stored in
# FONT16.BIN tiles HALF_TILE..HALF_TILE+11 (12 rarely used kanji). No per-pair font slots any more.
HALF_TILE = 0x168
HALF_TILES = 12
SPACE_PAIR_CODE = 1


def pair_code(pair):
    """Glyph code (tile + 1) for a 2-character pair: 0x8000 | c1 << 7 | c2, plus 1."""
    if pair == '  ':
        return SPACE_PAIR_CODE
    a, b = (ord(c) for c in pair)
    assert 0x20 <= a < 0x7F and 0x20 <= b < 0x7F, pair
    return (0x8000 | a << 7 | b) + 1


def half_font_bytes():
    out = bytearray()
    for c in range(0x20, 0x7F):
        ch = chr(c)
        grid = cell(ch) if ch in GLYPHS else [[0] * 8 for _ in range(16)]
        for row in grid:
            out.append(sum(bit << (7 - x) for x, bit in enumerate(row)))
    assert len(out) <= HALF_TILES * 128
    return bytes(out) + bytes(HALF_TILES * 128 - len(out))


def install_half_font(font):
    """Write the half-width font into a FONT16.BIN bytearray."""
    font[HALF_TILE * 128:(HALF_TILE + HALF_TILES) * 128] = half_font_bytes()
