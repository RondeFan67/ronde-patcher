def bitmap(ch):
    """8x8 list of 0/1 rows."""
    grid = [[0] * 8 for _ in range(8)]
    if ch in CAPS:
        top, rows = 1, CAPS[ch]
    else:
        top, rows = LOWER[ch]
    for r, line in enumerate(rows):
        for c, px in enumerate(line):
            if px == '#':
                grid[top + r][1 + c] = 1
    return grid


